#!/usr/bin/env python3
r"""Verify every number reported in paper/interconnect.md.

The paper's tables are generated by this script, not copied by hand.  Run:

    python interconnect/verify.py

It prints, in order: (1) the design table, (2) the hop-distance
distribution of each design, (3) the enumeration of difference covers,
(4) the threefold sumsets and the route table, (5) the Hall capacity and
sampled routability, (6) the degeneracy of the load-variance objective
used by interconnection.py, and (7) the cautionary offsets-modulo-N
design of multi_hop.py.

Conventions
-----------
Inputs are indexed 0..N-1, outputs 0..M-1.  A via exists at (i, j) iff
(j - i) mod M is in D, i.e. j = (i + d) mod M.  The loopback fabric is
the identity r -> r (it exists because M <= N).  A route's cost is the
number of vias it traverses (loopback edges are free).
"""
from __future__ import annotations

import random
from collections import Counter, deque
from itertools import combinations

D13 = (0, 1, 3, 9)          # Singer (13, 4, 1) difference set
D12 = (0, 1, 4, 6)          # near-cover modulo 12 used by the 41x12 script
D23 = (0, 1, 2, 3, 7, 11)   # difference cover modulo 23 (k = 6, minimal)

CASES = [
    ("13x13 core", 13, 13, D13),
    ("39x13 tiled", 39, 13, D13),
    ("38x13 truncated", 38, 13, D13),
    ("41x12 shipped", 41, 12, D12),
    ("41x12 best-spread", 41, 12, (0, 1, 3, 7)),
    ("41x12 k=5", 41, 12, (0, 1, 3, 5, 6)),
    ("13x13 k=5", 13, 13, (0, 1, 2, 6, 9)),
    ("100x23 mod-M", 100, 23, D23),
    ("100x23 best-spread", 100, 23, (0, 1, 3, 8, 12, 18)),
]


def grid(n: int, m: int, d) -> list[list[int]]:
    g = [[0] * m for _ in range(n)]
    for i in range(n):
        for off in d:
            g[i][(i + off) % m] = 1
    return g


def hop_distances(g, loopback=None):
    """Cost in vias from every input to every output, or None if unreachable."""
    n, m = len(g), len(g[0])
    if loopback is None:
        loopback = list(range(m))
    out = [[None] * m for _ in range(n)]
    for s in range(n):
        dist = {("i", s): 0}
        q = deque([("i", s)])
        while q:
            kind, x = q.popleft()
            d = dist[(kind, x)]
            if kind == "i":
                for j in range(m):
                    if g[x][j] and ("o", j) not in dist:
                        dist[("o", j)] = d + 1
                        q.append(("o", j))
            else:
                i2 = loopback[x]
                if ("i", i2) not in dist:
                    dist[("i", i2)] = d + 1
                    q.append(("i", i2))
        for j in range(m):
            if ("o", j) in dist:
                out[s][j] = (dist[("o", j)] + 1) // 2
    return out


def sharing(g):
    """Distribution of |outputs(i) & outputs(i')| over distinct input pairs."""
    n, m = len(g), len(g[0])
    hist = Counter()
    for i in range(n):
        for k in range(i + 1, n):
            common = sum(1 for x, y in zip(g[i], g[k]) if x and y)
            hist[common] += 1
    return hist


def covers(m: int, k: int):
    out = []
    for d in combinations(range(m), k):
        diffs = {(a - b) % m for a in d for b in d if a != b}
        if len(diffs) == m - 1:
            out.append(d)
    return out


def sum_cover(d, m: int) -> bool:
    return len({(a + b) % m for a in d for b in d}) == m


def sums(d, t: int, m: int) -> set:
    """t-fold sumset of d modulo m (with 0 in d, the sumsets are nested)."""
    s = {0}
    for _ in range(t):
        s = {(a + b) % m for a in s for b in d}
    return s


def is_cover(d, m: int) -> bool:
    return len({(a - b) % m for a in d for b in d if a != b}) == m - 1


def k_min(m: int) -> int:
    k = 2
    while k * (k - 1) < m - 1:
        k += 1
    return k


def normalized_covers(m: int, k: int):
    """All difference covers of size k that contain 0 (one per translation)."""
    for rest in combinations(range(1, m), k - 1):
        d = (0,) + rest
        if is_cover(d, m):
            yield d


def random_regular_fabric(m: int, k: int, rng) -> list:
    """A uniformly sampled simple k-regular bipartite graph, as row bitmasks."""
    while True:
        masks = [0] * m
        ok = True
        for _ in range(k):
            perm = list(range(m))
            rng.shuffle(perm)
            for i in range(m):
                masks[i] |= 1 << perm[i]
        for i in range(m):
            if masks[i].bit_count() != k:
                ok = False
                break
        if ok:
            return masks


def fabric_profile(m: int, k: int, trials: int, seed: int):
    """Mean <=2-via coverage and pairs sharing no output, over random fabrics."""
    rng = random.Random(seed)
    covered = 0
    no_share = 0
    best = 0
    for _ in range(trials):
        masks = random_regular_fabric(m, k, rng)
        reach = []
        for i in range(m):
            r = 0
            x = masks[i]
            while x:
                low = x & -x
                r |= masks[low.bit_length() - 1]
                x ^= low
            reach.append(r)
        two = 0
        for i in range(m):
            for j in range(m):
                if (masks[i] >> j) & 1 or (reach[i] >> j) & 1:
                    two += 1
        covered += two
        best = max(best, two)
        for i in range(m):
            for j in range(i + 1, m):
                if not (masks[i] & masks[j]):
                    no_share += 1
    return covered / (trials * m * m), no_share / trials, best / (m * m)


def capacity(n: int, m: int, d) -> int:
    """Hall capacity: largest c such that every <=c inputs have a matching.

    N(S) = R + D depends only on the residue set R, and the largest S with
    residue set R has min(C(R), m) elements.  Branch and bound over R.
    """
    c = [0] * m
    for i in range(n):
        c[i % m] += 1
    shifts = [sum(1 << ((r + x) % m) for x in d) for r in range(m)]
    best = min(n, m)

    def rec(start: int, mask: int, tot: int) -> None:
        nonlocal best
        nb = mask.bit_count()
        smax = min(tot, m)
        if smax and nb < smax and nb < best:
            best = nb
        if nb >= best:
            return
        for r in range(start, m):
            rec(r + 1, mask | shifts[r], tot + c[r])

    rec(0, 0, 0)
    return best


def max_matching(adj, m: int) -> int:
    """Size of a maximum matching (Kuhn's algorithm)."""
    match = [-1] * m

    def augment(u: int, seen: list) -> bool:
        for v in adj[u]:
            if seen[v]:
                continue
            seen[v] = True
            if match[v] == -1 or augment(match[v], seen):
                match[v] = u
                return True
        return False

    size = 0
    for u in range(len(adj)):
        if augment(u, [False] * m):
            size += 1
    return size


def routability(n: int, m: int, d, samples: int = 20000, seed: int = 11,
                signals: int = None) -> float:
    """Fraction of random input sets of the given size that admit a matching."""
    rng = random.Random(seed)
    adj_all = [[(i + x) % m for x in d] for i in range(n)]
    c = m if signals is None else signals
    ok = 0
    for _ in range(samples):
        chosen = rng.sample(range(n), c)
        if max_matching([adj_all[i] for i in chosen], m) == c:
            ok += 1
    return ok / samples


def main() -> None:
    print("=== 1. designs ==================================================")
    print(f"{'design':20s} {'N':>4s} {'M':>3s} {'k':>2s} {'V':>4s} "
          f"{'NM':>5s} {'rho':>6s} {'in':>5s} {'out':>7s} "
          f"{'share':>9s} {'1v':>4s} {'2v':>4s} {'3v':>4s} {'un':>4s}")
    for name, n, m, d in CASES:
        g = grid(n, m, d)
        v = sum(map(sum, g))
        din = [sum(row) for row in g]
        dout = [sum(g[i][j] for i in range(n)) for j in range(m)]
        dist = hop_distances(g)
        hist = Counter(x for row in dist for x in row)
        sh = sharing(g)
        shs = f"{min(sh)}-{max(sh)}"
        print(f"{name:20s} {n:4d} {m:3d} {len(d):2d} {v:4d} {n*m:5d} "
              f"{100*v/(n*m):5.1f}% {min(din):2d}-{max(din):2d} "
              f"{min(dout):2d}-{max(dout):2d} {shs:>9s} "
              f"{hist[1]:4d} {hist[2]:4d} {hist[3]:4d} {hist[None]:4d}")

    print("\n=== 2. pair multiplicities (13x13 and 39x13) ===================")
    for name, n, m, d in CASES[:3]:
        print(f"{name:20s}", dict(sorted(sharing(grid(n, m, d)).items())))

    print("\n=== 3. difference covers and sum covers ========================")
    for m, k in ((12, 4), (13, 4), (23, 6)):
        cs = covers(m, k)
        two = [d for d in cs if sum_cover(d, m)]
        print(f"M={m:2d} k={k}: {len(cs):5d} covers, "
              f"{len(cs)//m:4d} up to translation, "
              f"{len(two):3d} also sum covers")
        # best 2-via coverage on the square core
        best = None
        for d in cs:
            g = grid(m, m, d)
            dist = hop_distances(g)
            two_via = sum(1 for row in dist for x in row if x is not None and x <= 2)
            if best is None or two_via > best[0]:
                best = (two_via, d)
        print(f"          best 2-via coverage {best[0]}/{m*m} "
              f"({100*best[0]/(m*m):.1f}%) with D={best[1]}")
    print("smallest sum cover per modulus (exhaustive):")
    for m in (12, 13, 23):
        found = None
        for k in range(2, 9):
            if k * (k + 1) // 2 < m:
                continue
            for d in combinations(range(1, m), k - 1):
                cand = (0,) + d
                if sum_cover(cand, m):
                    found = (k, cand)
                    break
            if found:
                break
        print(f"  M={m:2d}: k={found[0]}, D={found[1]}, "
              f"vias per input = {found[0]}")

    print("\n=== 4. threefold sumsets and the route table ===================")
    for m, k in ((12, 4), (13, 4), (23, 6)):
        cs = covers(m, k)
        full = sum(1 for d in cs if len(sums(d, 3, m)) == m)
        print(f"M={m:2d} k={k}: 3D = Z_M for {full}/{len(cs)} covers")
    # boundary: minimum-size covers up to 31, one size larger up to 28
    bad = []
    for m in range(5, 32):
        k = k_min(m)
        n = 0
        for d in normalized_covers(m, k):
            n += 1
            if len(sums(d, 3, m)) < m:
                bad.append((m, k, d))
                break
        if m <= 28:
            for d in normalized_covers(m, k + 1):
                if len(sums(d, 3, m)) < m:
                    bad.append((m, k + 1, d))
                    break
    print("3D boundary: minimum-size covers M<=31 and one size larger M<=28")
    for m, k, d in bad:
        miss = sorted(set(range(m)) - sums(d, 3, m))
        print(f"  M={m} k={k} D={d}: missing {miss}, "
              f"pairs needing four vias = {m*len(miss)}")
    print(f"  counterexamples found: {len(bad)}")

    # counting bound at M = 20 is unattainable
    n5 = sum(1 for _ in normalized_covers(20, 5))
    print(f"M=20: 5-element covers = {n5} (bound allows k=5), "
          f"so the true minimum is 6")
    print("sufficient condition |D+D| > M-k for 3D = Z_M:")
    for m, d in ((12, D12), (13, D13), (23, D23), (23, (0, 1, 3, 8, 12, 18))):
        s2 = len(sums(d, 2, m))
        print(f"  M={m:2d} D={d}: |2D|={s2}, M-k={m-len(d)}, "
              f"holds={s2 > m - len(d)}")

    print("random 4-regular fabrics (Table III):")
    cov, share, best = fabric_profile(13, 4, 3000, seed=7)
    print(f"random 13x13, 4-regular, 3000 samples: mean <=2-via {100*cov:.1f}%, "
          f"best {100*best:.1f}%, pairs sharing nothing {share:.1f} of 78")
    # counterexample: a difference cover whose 3-fold sum is incomplete
    m, d = 28, (0, 9, 14, 20, 23, 25, 27)
    missing = sorted(set(range(m)) - sums(d, 3, m))
    print(f"M={m} D={d}: cover={is_cover(d, m)}, |D+D|={len(sums(d, 2, m))}, "
          f"|3D|={len(sums(d, 3, m))}, missing={missing}, |4D|={len(sums(d, 4, m))}")
    g = grid(m, m, d)
    dist = hop_distances(g)
    hist = Counter(x for row in dist for x in row)
    print(f"          hop histogram {dict(sorted(hist.items(), key=str))}")

    # a route table of M entries, built from the sumsets only (no BFS)
    for m, d in ((12, (0, 1, 4, 6)), (13, (0, 1, 3, 9)), (23, (0, 1, 2, 3, 7, 11))):
        table = {}
        for a in d:
            table.setdefault(a % m, (a,))
        for a in d:
            for b in d:
                table.setdefault((a + b) % m, (a, b))
        for a in d:
            for b in d:
                for c in d:
                    table.setdefault((a + b + c) % m, (a, b, c))
        # every entry must reproduce the BFS distance
        g = grid(m, m, d)
        dist = hop_distances(g)
        ok = all(dist[i][j] == len(table[(j - i) % m])
                 for i in range(m) for j in range(m))
        hist = Counter(len(v) for v in table.values())
        print(f"M={m:2d} D={d}: route table {len(table)}/{m} residues, "
              f"vias per entry {dict(sorted(hist.items()))}, matches BFS: {ok}")

    print("\n=== 5. Hall capacity and sampled routability ===================")
    for name, n, m, d in CASES:
        if "mod-M" in name or name.startswith("41x12") or name.startswith("13x13") \
           or name.endswith("tiled") or name.endswith("truncated"):
            cap = capacity(n, m, d)
            r = routability(n, m, d)
            print(f"{name:20s} N={n:3d} M={m:2d}: capacity={cap:2d}, "
                  f"routability at {m} signals={100*r:5.1f}%")

    print("\n=== 6. comparison at the dimensions of the PLD literature =======")
    for name, n, m in (("168x24 k=6", 168, 24), ("168x29 k=6", 168, 29)):
        cap = capacity(n, m, D23)
        r = routability(n, m, D23, signals=24)
        print(f"{name}: V={n*6}, capacity={cap}, routability at 24 signals={100*r:.1f}%")

    print("\n=== 7. load variance objective of interconnection.py ==========")
    n, m = 100, 23
    pos = [int(round(j * n / m)) % n for j in range(m)]
    cand = [x for x in (0, 1, 2, 4, 5, 8, 10, 12, 15, 20, 25, 33, 40, 50, 75)
            if x < n]
    variances = set()
    for d in combinations(cand, 6):
        counts = [0] * m
        for i in range(n):
            for j in range(m):
                if (i - pos[j]) % n in d:
                    counts[j] += 1
        variances.add(tuple(counts))
    print(f"{len(list(combinations(cand, 6)))} candidate sets, "
          f"{len(variances)} distinct output-load vectors, "
          f"all equal to (6,...,6): {variances == {(6,) * m}}")
    print(f"first combination accepted by the script: "
          f"{list(combinations(cand, 6))[0]}")

    print("\n=== 8. offsets modulo N (multi_hop.py) vs modulo M ============")
    d = (0, 4, 12, 25, 50, 75)
    g = [[0] * m for _ in range(n)]
    for i in range(n):
        for j in range(m):
            if (i - pos[j]) % n in d:
                g[i][j] = 1
    v = sum(map(sum, g))
    din = [sum(row) for row in g]
    loop = {j: pos[j] for j in range(m)}
    dist = hop_distances(g, [loop[j] for j in range(m)])
    hist = Counter(x for row in dist for x in row)
    print(f"modulo N: V={v}, inputs with no via={sum(1 for x in din if x == 0)}, "
          f"input loads {min(din)}-{max(din)}")
    print(f"          hops {dict((k, v) for k, v in sorted(hist.items(), key=str))}")
    print(f"          unreachable pairs {hist[None]}/{n*m}")
    g2 = grid(n, m, D23)
    dist2 = hop_distances(g2)
    hist2 = Counter(x for row in dist2 for x in row)
    print(f"modulo M: V={sum(map(sum, g2))}, "
          f"input loads {min(sum(r) for r in g2)}-{max(sum(r) for r in g2)}, "
          f"hops {dict(sorted(hist2.items(), key=str))}")


if __name__ == "__main__":
    main()
